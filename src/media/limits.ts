/**
 * Жёсткие пределы медиа. Не настраиваются окружением: прямое скачивание и
 * векторный поиск — разные бюджеты. Оригинал больше предела архива нельзя
 * получить даже по явному запросу; вложение больше предела эмбеддинга или
 * длиннее предела остаётся в архиве, но не участвует в поиске по смыслу.
 */

/** 2048 МиБ — предел оригинала, который сохраняется и отдаётся по ссылке. */
export const MEDIA_ARCHIVE_MAX_BYTES = 2_048 * 1_048_576;

/** 100 МиБ — предел вложения для векторного поиска. */
export const MEDIA_EMBED_MAX_BYTES = 100 * 1_048_576;

/** 1800 секунд — предел длительности вложения для векторного поиска. */
export const MEDIA_EMBED_MAX_SECONDS = 1_800;

/** Размер для сообщений об ошибках и причин пропуска. */
export function formatMediaSize(bytes: number): string {
  if (bytes >= 1_048_576) return `${(bytes / 1_048_576).toFixed(1)} МБ`;
  if (bytes >= 1_024) return `${(bytes / 1_024).toFixed(1)} КБ`;
  return `${bytes} байт`;
}
